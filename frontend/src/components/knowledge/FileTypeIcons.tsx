/**
 * 根据文件类型返回对应的图标组件
 */
export const FileTypeIcon: React.FC<{ type?: string; size?: number; className?: string }> = ({
    type,
    size = 16,
    className
}) => {
    switch (type?.toLowerCase()) {
        case 'docx':
        case 'doc':
            return <DocxIcon size={size} className={className} />;
        case 'xlsx':
        case 'xls':
        case 'csv':
            return <ExcelIcon size={size} className={className} />;
        case 'pdf':
            return <PdfIcon size={size} className={className} />;
        case 'txt':
            return <TxtIcon size={size} className={className} />;
        case 'md':
        case 'markdown':
            return <MdIcon size={size} className={className} />;
        default:
            return <GenericFileIcon size={size} className={className} />;
    }
};

export default FileTypeIcon;
